/**
 * fin_topic 주제표 — 자연어 질문에서 **조문 번호**까지 건너가는 다리
 *
 * 단절 지점은 검색어가 아니라 조문 번호다. fin_article은 law+article이 필수인데
 * 질문자는 번호를 모르고, fin_law_search는 법령명까지만 준다. 그 사이를 이 표가 잇는다.
 *
 * ⚠ 이 파일은 **큐레이션**이다 — 의미 검색이 아니라 사람이 적어 둔 표다. 그래서 낡는다.
 *   test/topic-articles-live.test.ts가 모든 (law, article)이 실존하고 조문 제목이 이 표의
 *   title과 일치하는지 실 API로 검증한다. 조문이 개정·이동하면 그 테스트가 먼저 깨진다.
 *
 * ⚠ 이 표는 **판정하지 않는다**. 답을 주는 것이 아니라 "무엇을 확인해야 하는지"와
 *   "다음에 무엇을 호출해야 하는지"만 준다. ✓·✗ 판정은 fin_verify의 몫이다.
 */

/** 조문 후보 하나 — 그대로 fin_article의 인자가 된다 */
export interface ArticleCandidate {
  /** fin_article의 law 인자 그대로 (약칭 금지 — 라이브 테스트가 이 표기로 조회한다) */
  law: string
  /** fin_article의 article 인자 그대로 (예: "제45조", "제10조의2") */
  article: string
  /**
   * 조문 제목 — 법제처 원문의 `제N조(제목)` 괄호 안 문자열과 정확히 같아야 한다.
   * 라이브 테스트의 대조 기준이자, 낡음을 감지하는 유일한 장치다.
   */
  title: string
  /** 왜 이 조문인가 — 조문 안의 어느 항·호가 쟁점인지까지 (예: "제1항 8호가 경조사비") */
  note: string
}

/** 업무 주제 하나 */
export interface Topic {
  /** 안정 식별자 (kebab-case) — 테스트·회귀 추적용. 표시하지 않는다 */
  id: string
  /** 표시 이름 (예: "임직원 경조사비") */
  name: string
  /**
   * 트리거 키워드 — **일상어를 반드시 포함**한다. 질문자는 "기업업무추진비"라고 쓰지 않고
   * "법인카드로 거래처 밥값"이라고 쓴다. 법령 용어만 넣으면 이 도구는 아무것도 매칭하지 못한다.
   * 매칭은 부분 문자열 포함으로 한다 (형태소 분석 없음).
   */
  triggers: string[]
  /**
   * 확인할 사실 — 답이 갈리는 분기점만. "· 사실 → 무엇으로 갈리는지" 형태로 적는다.
   * 답을 모르면 답할 수 없는 것만 넣는다 (형식적 체크리스트 금지).
   */
  checks: string[]
  /** 근거 조문 후보 — 실무에서 실제로 펴 보는 순서대로 */
  articles: ArticleCandidate[]
  /** 예규 검색어 (fin_ruling_search의 query) — 없으면 null */
  rulingQuery: string | null
  /** 검색어를 그것으로 고른 이유 (예: "축의금은 예규 제목에 드묾") */
  rulingNote?: string
  /** 연결되는 fin_calc의 calc_type — 없으면 null (지어내지 말 것: 지원 5종 외에는 null) */
  calc: string | null
  /** 계산 연결의 단서 (예: "거래처인 경우에만") */
  calcNote?: string
  /** 이 도구가 판단하지 않는 것 — 규범적 판단·사실 인정은 여기로 밀어낸다 */
  notJudged: string[]
}

